import io
import warnings
from PIL import Image, ImageStat, ImageFilter
from app.models.pest import ImageQualityAssessment

# Decompression bomb security limit: max 25 megapixels (e.g. 6000x4000)
# Prevents memory exhaustion attacks from malicious zip-bomb or decompression-bomb inputs
Image.MAX_IMAGE_PIXELS = 25_000_000
MAX_IMAGE_DIMENSION = 8000
MAX_FILE_SIZE_BYTES = 20 * 1024 * 1024  # 20 MB

# Set of recognized ISO BMFF HEIF/HEIC brand identifiers
HEIF_BRANDS = {b"heic", b"heix", b"hevc", b"hevx", b"mif1", b"msf1", b"heis", b"heim", b"hevd", b"hevs"}

def is_heic_image(image_bytes: bytes) -> bool:
    """
    Detects ISO Base Media File Format (ISO/IEC 14496-12) HEIC/HEIF brand signatures
    typically generated by Apple iOS default camera settings.
    Parses major brand and compatible brands while avoiding false positives on MP4/MOV video files.
    """
    if len(image_bytes) < 16:
        return False
    # ISO BMFF box structure: 4-byte box size, 4-byte box type 'ftyp'
    if image_bytes[4:8] != b"ftyp":
        return False
    
    # 1. Check major brand (bytes 8:12)
    major_brand = image_bytes[8:12]
    if major_brand in HEIF_BRANDS:
        return True
        
    # 2. Check compatible brands list (bytes 16:min(len, 64) in 4-byte strides)
    box_end = min(len(image_bytes), 64)
    for offset in range(16, box_end, 4):
        if offset + 4 <= len(image_bytes):
            comp_brand = image_bytes[offset:offset+4]
            if comp_brand in HEIF_BRANDS:
                return True
                
    return False

def validate_image_bytes(image_bytes: bytes) -> ImageQualityAssessment:
    """
    Evaluates complete image integrity, format compatibility, and optical quality on server side:
    - Verifies file size limits (<= 20MB)
    - Detects iOS HEIC/HEIF inputs and returns actionable guidance (native HEIC not supported)
    - Enforces decompression bomb bounds (max 25M pixels, max 8000px dimension)
    - Explicitly intercepts both Image.DecompressionBombWarning and Image.DecompressionBombError
    - Performs FULL raster decode (image.load()) to catch truncated JPEGs and corrupted streams
    - Measures calibrated luminance, contrast variance, and edge gradients
    - Documents raw scientific metrics (luminance 0-255, contrast stddev, Laplacian edge variance)
    """
    if not image_bytes or len(image_bytes) == 0:
        return ImageQualityAssessment(
            is_clear=False,
            lighting_score=0,
            sharpness_score=0,
            warning_message_en="Image file is empty (0 bytes). Please upload a valid photograph.",
            warning_message_or="ଫଟୋ ଫାଇଲଟି ସମ୍ପୂର୍ଣ୍ଣ ଖାଲି (୦ ବାଇଟ୍) ଅଟେ।"
        )

    if len(image_bytes) > MAX_FILE_SIZE_BYTES:
        return ImageQualityAssessment(
            is_clear=False,
            lighting_score=0,
            sharpness_score=0,
            warning_message_en=f"Image file exceeds maximum allowable limit of 20MB (Received {len(image_bytes)/(1024*1024):.1f}MB).",
            warning_message_or="ଫଟୋ ଫାଇଲର ଆକାର ସର୍ବାଧିକ ୨୦ MB ରୁ ଅଧିକ ଅଟେ।"
        )

    if len(image_bytes) < 16:
        return ImageQualityAssessment(
            is_clear=False,
            lighting_score=0,
            sharpness_score=0,
            warning_message_en="Image file is truncated or corrupted (insufficient header bytes).",
            warning_message_or="ଫଟୋ ଫାଇଲଟି ତ୍ରୁଟିପୂର୍ଣ୍ଣ ଅଟେ।"
        )

    # Detect iOS HEIC format
    if is_heic_image(image_bytes):
        return ImageQualityAssessment(
            is_clear=False,
            lighting_score=0,
            sharpness_score=0,
            warning_message_en=(
                "HEIC/HEIF format detected from iPhone/iOS. Native HEIC decoding is not supported by the vision pipeline. "
                "Please configure iPhone Settings > Camera > Formats to 'Most Compatible' (JPEG), or export as JPG before uploading."
            ),
            warning_message_or="ଆଇଫୋନରୁ HEIC ଫର୍ମାଟ୍ ଚିହ୍ନଟ ହୋଇଛି। ଏହି ଫର୍ମାଟ୍ ସିଧାସଳଖ ସମର୍ଥିତ ନୁହେଁ। ଦୟାକରି ଆଇଫୋନ୍ ସେଟିଙ୍ଗ୍‌ରେ 'Most Compatible' (JPEG) ବାଛନ୍ତୁ କିମ୍ବା JPG ଭାବେ ଅପଲୋଡ୍ କରନ୍ତୁ।"
        )

    try:
        # Catch Pillow decompression-bomb warnings and convert them to explicit rejections
        # without globally altering warning filters
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            image = Image.open(io.BytesIO(image_bytes))
            fmt = (image.format or "").upper()
            
            # Verify supported image codecs
            if fmt not in ["JPEG", "PNG", "WEBP", "MPO"]:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=0,
                    sharpness_score=0,
                    warning_message_en=f"Unsupported format '{fmt}'. Only genuine JPEG, PNG, and WEBP photographs are supported.",
                    warning_message_or=f"ଅସମର୍ଥିତ ଫର୍ମାଟ୍ ({fmt})। କେବଳ JPEG, PNG କିମ୍ବା WEBP ଫଟୋ ସମର୍ଥିତ।"
                )

            width, height = image.size
            total_pixels = width * height

            # Explicit check on 25MP decompression bomb limit
            if total_pixels > Image.MAX_IMAGE_PIXELS:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=0,
                    sharpness_score=0,
                    warning_message_en=f"Decompression bomb rejected: Image has {total_pixels:,} pixels, exceeding limit of {Image.MAX_IMAGE_PIXELS:,} pixels (25MP).",
                    warning_message_or="ଅତ୍ୟଧିକ ପିକ୍ସେଲ (୨୫ ମେଗାପିକ୍ସେଲରୁ ଅଧିକ) ଯୋଗୁଁ ଫଟୋ ପ୍ରତ୍ୟାଖ୍ୟାନ କରାଗଲା।"
                )
            
            # Lower dimension bound
            if width < 32 or height < 32:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=0,
                    sharpness_score=0,
                    warning_message_en=f"Image dimensions ({width}x{height}) are too small (minimum 32x32 required for insect recognition).",
                    warning_message_or="ଫଟୋର ଆକାର ବହୁତ ଛୋଟ ଅଟେ। ଅନ୍ତତଃ ସ୍ପଷ୍ଟ କ୍ୟାମେରା ଫଟୋ ଅପଲୋଡ୍ କରନ୍ତୁ।"
                )

            # Upper dimension bound (excessive dimension protection)
            if width > MAX_IMAGE_DIMENSION or height > MAX_IMAGE_DIMENSION:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=0,
                    sharpness_score=0,
                    warning_message_en=f"Image dimensions ({width}x{height}) exceed maximum allowed dimension of {MAX_IMAGE_DIMENSION}px.",
                    warning_message_or=f"ଫଟୋର ଆକାର ସର୍ବାଧିକ {MAX_IMAGE_DIMENSION} ପିକ୍ସେଲରୁ ଅଧିକ ଅଟେ।"
                )

            # FULL RASTER DECODE: forces complete decompression of all pixel scans
            # Catches truncated JPEGs, corrupted scanlines, and valid headers with invalid bodies
            image.load()

            image_rgb = image.convert("RGB")
            
            # Resize thumbnail for fast optical metric calculation
            thumb = image_rgb.resize((160, 120))
            stat = ImageStat.Stat(thumb)
            
            # Luminance based on standard Rec. 601 coefficients
            r, g, b = stat.mean[:3]
            avg_brightness = (r * 0.299 + g * 0.587 + b * 0.114)
            lighting_score = min(100, max(1, int(round((avg_brightness / 255.0) * 100))))
            
            # Contrast variance for dynamic range (standard deviation of RGB channels)
            stddev = stat.stddev
            avg_contrast = (stddev[0] + stddev[1] + stddev[2]) / 3.0

            # High-frequency edge content via FIND_EDGES on grayscale
            gray = image_rgb.convert("L")
            edge_filter = gray.filter(ImageFilter.FIND_EDGES)
            edge_stat = ImageStat.Stat(edge_filter)
            edge_mean = edge_stat.mean[0]
            edge_var = edge_stat.var[0] if hasattr(edge_stat, "var") and edge_stat.var else (edge_mean ** 2)
            sharpness_score = min(100, max(1, int(round((edge_mean / 6.0) * 100))))

            raw_metrics = {
                "raw_mean_luminance": round(float(avg_brightness), 2),
                "raw_contrast_std": round(float(avg_contrast), 2),
                "raw_edge_variance": round(float(edge_var), 2)
            }
            
            # Blank / solid color check (variance almost zero)
            if avg_contrast < 2.5:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=lighting_score,
                    sharpness_score=sharpness_score,
                    warning_message_en="The uploaded photograph appears completely uniform or empty. No agricultural subject detected.",
                    warning_message_or="ଫଟୋଟି ସମ୍ପୂର୍ଣ୍ଣ ଖାଲି କିମ୍ବା ଏକା ରଙ୍ଗର ଦେଖାଯାଉଛି। କୌଣସି ଫସଲ କିମ୍ବା ପୋକ ଚିହ୍ନଟ ହେଲାନାହିଁ।",
                    **raw_metrics
                )

            # Calibrated blur check: edge_mean below 1.8 indicates extreme blur lacking diagnostic anatomy
            if sharpness_score < 28 or edge_mean < 1.8:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=lighting_score,
                    sharpness_score=sharpness_score,
                    warning_message_en="Warning: The photograph appears blurry or out of focus. Fine entomological features cannot be distinguished.",
                    warning_message_or="ସତର୍କତା: ଫଟୋଟି ଝାପ୍‌ସା କିମ୍ବା ଅସ୍ପଷ୍ଟ ଦେଖାଯାଉଛି। ପୋକର ସୂକ୍ଷ୍ମ ଚିହ୍ନଟ ପାଇଁ ସ୍ଥିର ଭାବେ ଫଟୋ ନିଅନ୍ତୁ।",
                    **raw_metrics
                )
                
            # Calibrated underexposure (extreme pitch dark < 12%)
            # Allows overcast, early morning, or canopy-shaded field photos (14-85% lighting) to pass safely
            if lighting_score < 12:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=lighting_score,
                    sharpness_score=sharpness_score,
                    warning_message_en="Warning: The photograph is severely underexposed (too dark). Pest color patterns cannot be distinguished.",
                    warning_message_or="ସତର୍କତା: ଫଟୋଟି ବହୁତ ଅନ୍ଧକାରରେ ଉଠାଯାଇଛି। ଦିନ ଆଲୋକରେ ପୁଣି ଫଟୋ ଉଠାନ୍ତୁ।",
                    **raw_metrics
                )

            # Severe overexposure (washed out white with no contrast)
            if avg_brightness > 248 and avg_contrast < 8.0:
                return ImageQualityAssessment(
                    is_clear=False,
                    lighting_score=lighting_score,
                    sharpness_score=sharpness_score,
                    warning_message_en="Warning: The photograph is washed out by excessive direct camera flash or sun glare.",
                    warning_message_or="ସତର୍କତା: ଫଟୋରେ ଅତ୍ୟଧିକ ଆଲୋକ ବା ଫ୍ଲାସ୍ ଚମକ ଯୋଗୁଁ ବିବରଣୀ ସ୍ପଷ୍ଟ ନାହିଁ।",
                    **raw_metrics
                )
            
            return ImageQualityAssessment(
                is_clear=True,
                lighting_score=lighting_score,
                sharpness_score=sharpness_score,
                **raw_metrics
            )
    except (Image.DecompressionBombError, Image.DecompressionBombWarning) as e:
        return ImageQualityAssessment(
            is_clear=False,
            lighting_score=0,
            sharpness_score=0,
            warning_message_en="Decompression bomb rejected: Image pixel count exceeds maximum allowable safety limit of 25 megapixels.",
            warning_message_or="ଅତ୍ୟଧିକ ପିକ୍ସେଲ (୨୫ ମେଗାପିକ୍ସେଲରୁ ଅଧିକ) ଯୋଗୁଁ ଫଟୋ ପ୍ରତ୍ୟାଖ୍ୟାନ କରାଗଲା।"
        )
    except Exception as e:
        return ImageQualityAssessment(
            is_clear=False,
            lighting_score=0,
            sharpness_score=0,
            warning_message_en=f"Invalid or corrupted image format: {str(e)}",
            warning_message_or="ଅପଲୋଡ୍ କରାଯାଇଥିବା ଫଟୋ ଫର୍ମାଟ୍ ତ୍ରୁଟିପୂର୍ଣ୍ଣ ଅଟେ।"
        )
